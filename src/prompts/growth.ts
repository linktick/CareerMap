import type { CareerRoute, UserProfile } from '@/types/career'

export function buildGrowthPrompt(profile: UserProfile, route: CareerRoute): string {
  return `请为下面这位用户，针对指定职业路线，生成未来 12 个月按月拆分的能力成长方案。

要求：
- 每月一个明确主题
- 学习任务要具体到技术/工具/知识点，不要"提升沟通能力"这种空话
- 实践项目要可独立完成，1~2 个
- 求职动作按月推进（简历→作品集→投递→面试→谈薪）
- 证书备考要给具体月份区间，没有行业公认证书就返回空字符串
- 月度重点提醒要说真话：常见误区、时间分配、避坑点
- 用户已掌握的技能，相关任务标注为"review"而非"new"

【工作年限铁律 —— 必须结合用户资历生成，严禁所有人都从零基础第一年开始】
用户信息中 yearsOfExperience 单位为「月」（÷12 = 工作年数），skills 为已掌握技能：
- 普通职场路线：已有 N 年相关经验的用户，12 个月计划必须从其当前资历的「下一台阶」起步——已有 3 年经验者严禁出现"了解岗位是什么/零基础入门/HTML 入门"这类内容；已掌握技能的任务标注"review"；targetRole/targetSalary 对齐 12 个月后（更高一级）的资历段，求职动作按"晋升/跳槽涨薪"而非"应届找工作"编排。
- 转行用户（目标岗位与其专业/技能背景不相关）：可安排新领域入门内容，但必须利用其可迁移职场能力，不得写成应届生校招方案。
- 体制内考试路线（公务员/事业编/教师编）：备考内容从零起步（往届工龄不抵考编），但要结合在职状态——如在职备考的时间管理、职场经验在结构化面试中的优势。

【体制内考试方向特殊规则 —— 路线为公务员/事业编/事业单位/选调生/教师编等时必须遵守】
这类路线的 12 个月方案是「公考/考编备考方案」，不是职场技能成长方案，严禁出现"投递简历/作品集/入职公司"等职场求职内容：
- 学习任务围绕考试科目展开：行测六大模块——言语理解、判断推理、资料分析、数量关系、常识判断、政治理论（时政方针、重要会议精神等，2025 年起国考新增模块）；申论（归纳概括、综合分析、提出对策、贯彻执行/公文写作、大作文）；时政积累；事业单位加试的公共基础知识；后期转为结构化面试/无领导小组讨论
- 报考门槛口径必须为最新：公务员/事业单位报考年龄一般为 18~38 周岁（应届硕士、博士可放宽至 42 周岁，具体以当年公告为准），选岗/报名相关内容按此口径，严禁出现"35 岁不能报考"之类过时说法
- 实践项目改为备考动作：真题套卷限时训练、全真模考、错题本、申论批改、面试模拟
- 求职动作（jobActions）改为考公节点：查职位表选岗报名、笔试、资格复审、面试、体检政审，按真实时间线排布（国考 10 月中旬报名、11 月底笔试；省考联考多在次年 3 月；事业单位公告全年滚动、上半年 3~5 月较集中）
- 公务员方向没有行业必考证书，certPrep 一律返回空字符串
- 教师编方向必须按真实考证考编顺序编排，月份先后不得颠倒：
  ① 普通话水平测试（语文/幼教需二级甲等，其他学科二级乙等，是教资认定必备材料）→
  ② 教师资格证：笔试（综合素质 + 教育知识与能力，中学加考学科知识）→ 面试（结构化问答 + 试讲 + 答辩）→ 体检认定拿证（笔试每年 3 月、9 月，面试 5 月、12 月~次年 1 月）→
  ③ 教师招聘考试（教育综合知识 + 学科专业知识笔试；面试试讲/说课 + 结构化；公告集中在 3~8 月，9 月上岗）→
  ④ 未上岸备选：特岗教师、三支一扶支教、民办学校/教培机构先就业。
  certPrep 写普通话证书/教师资格证备考节点，jobActions 写教资/教招报名、笔试、面试、认定、体检政审等节点；若用户 skills/简历中已体现持有教师资格证，直接从③教师招聘备考开始，不得再安排考教资
- targetRole 写"试用期公务员/事业编专技岗/在编教师"等上岸后身份，targetSalary 对齐路线 year1 薪资

返回 JSON 严格结构：
{
  "routeId": "路线id",
  "routeName": "路线名",
  "targetRole": "12个月后目标岗位",
  "goalSummary": "12个月总目标，50字以内",
  "targetSalary": [minK, maxK],
  "months": [
    {
      "month": 1,
      "theme": "本月主题",
      "learningTasks": [{"task":"具体任务","done":false,"type":"new|review"}],
      "practiceProjects": ["项目1"],
      "jobActions": "求职动作，没有则空字符串",
      "certPrep": "证书备考内容，无则空字符串",
      "keyReminder": "本月重点提醒，一句话真话"
    }
  ]
}

用户信息：${JSON.stringify(profile)}
选定路线：${JSON.stringify(route)}

只输出 JSON 对象。`
}
